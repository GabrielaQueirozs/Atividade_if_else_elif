numero = int(input("Digite um número de 1 a 7: "))

if numero == 1:
    print("SEGUNDA-FEIRA")

elif numero == 2:
    print("TERÇA-FEIRA")

elif numero == 3:
    print("QUARTA-FEIRA")

elif numero == 4:
    print("QUINTA-FEIRA")

elif numero == 5:
    print("SEXTA-FEIRA")

elif numero == 6:
    print("SÁBADO")

elif numero == 7:
    print("DOMINGO")

else:
    print("OPÇÃO INVÁLIDA")